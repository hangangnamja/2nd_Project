namespace Game.Battle
{
    // 효과가 어떤 행동에서 나왔는지 (발생 원인). 반응 패시브가 이 효과에 반응해도 되는지 판단하는 데 쓴다.
    public enum ActionSource
    {
        // 플레이어·AI가 고른 스킬
        Skill,

        // 패시브로 나간 추가 공격. "공격 판정 시"·"처치 시" 반응은 일으키지만,
        // "아군 공격 시" 반응은 정규 스킬에만 발동하므로 일으키지 않는다 (기획서 3-4).
        FollowUpAttack,

        // 패시브에 붙은 효과 (화상 부여 등). 공격 행동이 아니므로 반응을 일으키지 않는다.
        PassiveEffect,
    }
}
